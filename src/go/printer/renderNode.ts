import * as DPattern from "@duplojs/lang/pattern";
import { type Node } from "../AST";
import { createPrinterContext } from "./createPrinterContext";
import * as DeclarationPrinter from "./declaration";
import * as ExpressionPrinter from "./expression";
import { printFile } from "./printFile";
import { printFunctionArgument } from "./printFunctionArgument";
import { printIdentifier } from "./printIdentifier";
import { printImportDeclaration } from "./printImportDeclaration";
import * as StatementPrinter from "./statement";
import * as TypePrinter from "./type";

export function renderNode(node: Node, depth = 0): string {
	const context = createPrinterContext(
		depth,
		(child, childDepth = depth) => renderNode(child, childDepth),
	);
	return DPattern.matchWithTaggedObject(node, {
		"[node]function-argument": printFunctionArgument(context),
		"[node][declaration][statement]constant": DeclarationPrinter.printConstantDeclaration(context),
		"[node][declaration]function": DeclarationPrinter.printFunctionDeclaration(context),
		"[node][declaration]method": DeclarationPrinter.printMethodDeclaration(context),
		"[node][declaration][statement]type": DeclarationPrinter.printTypeDeclaration(context),
		"[node][declaration][statement]type-alias": DeclarationPrinter.printTypeAliasDeclaration(context),
		"[node][declaration][statement]variable-zero-value": DeclarationPrinter.printVariableDeclarationZeroValue(context),
		"[node][declaration][statement]variable-initialized": DeclarationPrinter.printVariableDeclarationInitialized(context),
		"[node][expression]selector": ExpressionPrinter.printSelectorExpression(context),
		"[node][expression]method": ExpressionPrinter.printMethodExpression(context),
		"[node][expression]index": ExpressionPrinter.printIndexExpression(context),
		"[node][expression]slice": ExpressionPrinter.printSliceExpression(context),
		"[node][expression]slice-full": ExpressionPrinter.printFullSliceExpression(context),
		"[node][expression]type-assertion": ExpressionPrinter.printTypeAssertionExpression(context),
		"[node][expression][statement]call": ExpressionPrinter.printCallExpression(context),
		"[node]literal-element-keyed": ExpressionPrinter.printKeyedElement(context),
		"[node][expression]literal-array": ExpressionPrinter.printArrayLiteral(context),
		"[node][expression]literal-slice": ExpressionPrinter.printSliceLiteral(context),
		"[node][expression]literal-map": ExpressionPrinter.printMapLiteral(context),
		"[node][expression]literal-struct": ExpressionPrinter.printStructLiteral(context),
		"[node][expression]conversion": ExpressionPrinter.printConversionExpression(context),
		"[node][expression]literal-function": ExpressionPrinter.printFunctionLiteral(context),
		"[node][expression]instantiation": ExpressionPrinter.printInstantiationExpression(context),
		"[node][expression]literal-integer": ExpressionPrinter.printIntegerLiteral(context),
		"[node][expression]literal-float": ExpressionPrinter.printFloatLiteral(context),
		"[node][expression]literal-imaginary": ExpressionPrinter.printImaginaryLiteral(context),
		"[node][expression]literal-rune": ExpressionPrinter.printRuneLiteral(context),
		"[node][expression]literal-string": ExpressionPrinter.printStringLiteral(context),
		"[node][expression]literal-boolean": ExpressionPrinter.printBooleanLiteral(context),
		"[node][expression]literal-nil": ExpressionPrinter.printNilLiteral(context),
		"[node][expression]unary": ExpressionPrinter.printUnaryExpression(context),
		"[node][expression]binary": ExpressionPrinter.printBinaryExpression(context),
		"[node][expression]address": ExpressionPrinter.printAddressExpression(context),
		"[node][expression]dereference": ExpressionPrinter.printDereferenceExpression(context),
		"[node][expression][statement]receive": ExpressionPrinter.printReceiveExpression(context),
		"[node]file": printFile(context),
		"[node]identifier": printIdentifier(context),
		"[node]import": printImportDeclaration(context),
		"[node][statement]assignment": StatementPrinter.printAssignmentStatement(context),
		"[node][statement]assignment-compound": StatementPrinter.printCompoundAssignmentStatement(context),
		"[node][statement]variable-short": StatementPrinter.printShortVariableDeclarationStatement(context),
		"[node][statement]block": StatementPrinter.printBlockStatement(context),
		"[node][statement]go": StatementPrinter.printGoStatement(context),
		"[node][statement]defer": StatementPrinter.printDeferStatement(context),
		"[node][statement]send": StatementPrinter.printSendStatement(context),
		"[node][statement]for": StatementPrinter.printForStatement(context),
		"[node]range-assignment": StatementPrinter.printRangeAssignment(context),
		"[node]range-declaration": StatementPrinter.printRangeDeclaration(context),
		"[node][statement]range": StatementPrinter.printRangeStatement(context),
		"[node][statement]if": StatementPrinter.printIfStatement(context),
		"[node][statement]return": StatementPrinter.printReturnStatement(context),
		"[node][statement]break": StatementPrinter.printBreakStatement(context),
		"[node][statement]continue": StatementPrinter.printContinueStatement(context),
		"[node][statement]goto": StatementPrinter.printGotoStatement(context),
		"[node][statement]fallthrough": StatementPrinter.printFallthroughStatement(context),
		"[node][statement]labeled": StatementPrinter.printLabeledStatement(context),
		"[node]select-receive-assignment": StatementPrinter.printSelectReceiveAssignment(context),
		"[node]select-receive-declaration": StatementPrinter.printSelectReceiveDeclaration(context),
		"[node]select-case": StatementPrinter.printSelectCase(context),
		"[node][statement]select-without-default": StatementPrinter.printSelectStatementWithoutDefault(context),
		"[node][statement]select-with-default": StatementPrinter.printSelectStatementWithDefault(context),
		"[node]switch-case-expression": StatementPrinter.printExpressionSwitchCase(context),
		"[node]case-default": StatementPrinter.printDefaultCase(context),
		"[node][statement]switch-expression-without-default": StatementPrinter.printExpressionSwitchStatementWithoutDefault(context),
		"[node][statement]switch-expression-with-default": StatementPrinter.printExpressionSwitchStatementWithDefault(context),
		"[node]switch-case-type": StatementPrinter.printTypeSwitchCase(context),
		"[node][statement]switch-type-without-default": StatementPrinter.printTypeSwitchStatementWithoutDefault(context),
		"[node][statement]switch-type-with-default": StatementPrinter.printTypeSwitchStatementWithDefault(context),
		"[node][type]array": TypePrinter.printArrayType(context),
		"[node][type]channel": TypePrinter.printChannelType(context),
		"[node]type-constraint": TypePrinter.printTypeConstraint(context),
		"[node][type]function": TypePrinter.printFunctionType(context),
		"[node]interface-method": TypePrinter.printInterfaceMethod(context),
		"[node]interface-union": TypePrinter.printInterfaceUnion(context),
		"[node][type]interface": TypePrinter.printInterfaceType(context),
		"[node][type]map": TypePrinter.printMapType(context),
		"[node][type]pointer": TypePrinter.printPointerType(context),
		"[node]type-reference-package": TypePrinter.printPackageTypeReference(context),
		"[node]type-reference-generic": TypePrinter.printGenericTypeReference(context),
		"[node][type]slice": TypePrinter.printSliceType(context),
		"[node]struct-field": TypePrinter.printStructField(context),
		"[node]struct-embedded-field": TypePrinter.printStructEmbeddedField(context),
		"[node][type]struct": TypePrinter.printStructType(context),
	});
}
