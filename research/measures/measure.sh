#!/usr/bin/env bash
# Mesures de bout en bout (PLAN §10) : Node via tsx, Node sur JS compilé (bundle esbuild),
# et binaire Go (go build), sur les exercices passés en argument.
#
# Usage : ./research/measures/measure.sh [--runs N] [01 05 09 10]   (N par défaut : 30)
# Sortie : tableau Markdown sur la sortie standard, et research/measures/results.md.
#
# Temps : hyperfine s'il est installé ; sinon, boucle chronométrée (médiane, min, max) :
# chaque exécution est un processus complet, démarrage compris.
# Mémoire : maximum resident set size de /usr/bin/time (-l sur macOS, -v sur Linux).
# Échappements : lignes « escapes to heap » de go build -gcflags=-m, hors runtime partagé
# (./shard_dependencies/) et enveloppes générées par Go (<autogenerated>).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
RUNS=30
if [[ "${1:-}" == "--runs" ]]; then RUNS="$2"; shift 2; fi
IDS=("$@"); [[ ${#IDS[@]} -gt 0 ]] || IDS=(01 05 09 10)

WORK="$(mktemp -d "${TMPDIR:-/tmp}/measures.XXXXXX")"
trap 'rm -rf "$WORK"' EXIT
ESBUILD="$(ls -d "$ROOT"/node_modules/.pnpm/esbuild@*/node_modules/esbuild/bin/esbuild | head -1)"
TSX="$ROOT/node_modules/.bin/tsx"

max_rss_kb() {
	if [[ "$(uname)" == Darwin ]]; then
		/usr/bin/time -l "$@" 2>&1 >/dev/null | awk '/maximum resident set size/ { printf "%d", $1 / 1024 }'
	else
		/usr/bin/time -v "$@" 2>&1 >/dev/null | awk -F: '/Maximum resident set size/ { gsub(/ /, "", $2); printf "%d", $2 }'
	fi
}

# Médiane, min et max en millisecondes de RUNS exécutions (après 3 échauffements).
timing() {
	if command -v hyperfine > /dev/null; then
		hyperfine --style none --warmup 3 --runs "$RUNS" --export-json "$WORK/h.json" -- "$*" > /dev/null
		python3 -c 'import json,sys; r=json.load(open(sys.argv[1]))["results"][0]; t=sorted(r["times"]); print("%.1f [%.1f..%.1f]" % (r["median"]*1e3, t[0]*1e3, t[-1]*1e3))' "$WORK/h.json"
	else
		python3 - "$RUNS" "$@" <<'PY'
import subprocess, sys, time, statistics
runs, cmd = int(sys.argv[1]), sys.argv[2:]
for _ in range(3):
    subprocess.run(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=True)
times = []
for _ in range(runs):
    start = time.perf_counter()
    subprocess.run(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=True)
    times.append((time.perf_counter() - start) * 1e3)
print("%.1f [%.1f..%.1f]" % (statistics.median(times), min(times), max(times)))
PY
	fi
}

ROWS=()
for id in "${IDS[@]}"; do
	project="$ROOT/projects/$id"
	echo "[$id] transpilation, compilation et vérification…" >&2
	(cd "$ROOT" && pnpm --silent run build --tsconfig "projects/$id/tsconfig.json" --input "projects/$id/index.ts" --output "projects/$id/dist") > "$WORK/$id.build.log" 2>&1 \
		|| { echo "[$id] transpilation en échec : ignoré" >&2; ROWS+=("| $id | – | – | – | – | – | – | transpilation en échec |"); continue; }
	(cd "$project/dist" && go build -o "$WORK/$id-go" .)
	"$ESBUILD" "$project/index.ts" --bundle --platform=node --format=esm --log-level=error --outfile="$WORK/$id.mjs"

	# Les trois versions doivent produire la même sortie avant toute mesure.
	(cd "$ROOT" && "$TSX" --tsconfig "projects/$id/tsconfig.json" "projects/$id/index.ts") > "$WORK/$id.tsx.txt"
	node "$WORK/$id.mjs" > "$WORK/$id.node.txt"
	"$WORK/$id-go" > "$WORK/$id.go.txt"
	cmp -s "$WORK/$id.tsx.txt" "$WORK/$id.node.txt" && cmp -s "$WORK/$id.tsx.txt" "$WORK/$id.go.txt" \
		|| { echo "[$id] sorties différentes : ignoré" >&2; ROWS+=("| $id | – | – | – | – | – | – | sorties différentes |"); continue; }

	echo "[$id] mesures ($RUNS exécutions par version)…" >&2
	t_tsx="$(cd "$ROOT" && timing "$TSX" --tsconfig "projects/$id/tsconfig.json" "projects/$id/index.ts")"
	t_node="$(timing node "$WORK/$id.mjs")"
	t_go="$(timing "$WORK/$id-go")"
	m_node="$(max_rss_kb node "$WORK/$id.mjs")"
	m_go="$(max_rss_kb "$WORK/$id-go")"
	# Code utilisateur : fichiers transpilés depuis projects/XX ; exclut ./shard_dependencies/
	# (runtime partagé) et <autogenerated> (enveloppes de méthodes générées par Go).
	escapes="$(cd "$project/dist" && go build -gcflags=-m ./... 2>&1 \
		| grep 'escapes to heap' | grep -v -e 'shard_dependencies/' -e '^<autogenerated>' -c || true)"
	ROWS+=("| $id | $t_tsx | $t_node | $t_go | $(( m_node / 1024 )) | $(( m_go / 1024 )) | $escapes | |")
done

{
	echo "Machine : $(if [[ "$(uname)" == Darwin ]]; then sysctl -n machdep.cpu.brand_string; echo -n ", macOS $(sw_vers -productVersion)"; else uname -srm; fi | tr '\n' ' ')· $(go version | cut -d' ' -f3-4) · Node $(node --version) · $(command -v hyperfine > /dev/null && echo hyperfine || echo 'boucle Python (hyperfine absent)') · $RUNS exécutions par mesure · $(date '+%Y-%m-%d')"
	echo
	echo "| Ex. | Node + tsx (ms) | Node, JS compilé (ms) | Go, binaire (ms) | RSS max Node (Mo) | RSS max Go (Mo) | « escapes to heap » (code utilisateur) | Remarque |"
	echo "|---|---:|---:|---:|---:|---:|---:|---|"
	printf '%s\n' "${ROWS[@]}"
	echo
	echo "Temps : médiane [min..max] d'un processus complet (démarrage compris)."
} | tee "$ROOT/research/measures/results.md"
